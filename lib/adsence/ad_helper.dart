      return Platform.isAndroid
          ? 'ca-app-pub-3940256099942544/1033173712'
          : 'ca-app-pub-3940256099942544/4411468910';
    }
  }

  // mbannerのバナー広告ユニットID
  static String get mbannerAdUnitId {
